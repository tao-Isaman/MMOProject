// Writes src/world_index.ts: where each map's ways out lead (for the quest guide's route from map
// to map, and the ship captains for the places only a ship reaches) and the place each
// townsperson stands at, the nearest of the map's labels (for the quest texts). Loads every map in the running dev server (127.0.0.1:8766, or PORT). Run it again
// after moving a townsperson, a label or a way out.
//
//   node tools/world_index.cjs
const { chromium } = require(process.env.PLAYWRIGHT ?? "/opt/node22/lib/node_modules/playwright");
const fs = require("fs");
const path = require("path");
(async () => {
  const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
  const page = await (await browser.newContext()).newPage();
  page.setDefaultTimeout(600000);
  await page.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
  await page.goto(`http://127.0.0.1:${process.env.PORT || 8766}/`);
  await page.waitForSelector(".title-create, .title-chars", { timeout: 120000 });
  const data = await page.evaluate(async () => {
    const M = await import("/src/maps.ts");
    const { jobMasters } = await import("/src/jobmasters.ts");
    const out = { links: {}, ships: {}, places: {} };
    for (const id of Object.keys(M.MAP_NAMES)) {
      const map = await M.loadMap(id, { flowers: 0 });
      out.links[id] = [...new Set(map.warps.map((w) => w.to))];
      // a gate's label reads "ประตูเหนือ · ขอบทะเลทราย": the part before the dot names the spot
      const labels = map.labels.map((l) => ({ x: l.x, y: l.y, text: l.text.split(" · ")[0] }));
      // (the third jobs' masters join the townsfolk from their own list, as main.ts does)
      for (const n of [...map.npcs, ...jobMasters(id)]) {
        const near = labels.reduce((b, l) => (!b || Math.hypot(l.x - n.x, l.y - n.y) < Math.hypot(b.x - n.x, b.y - n.y) ? l : b), null);
        if (near) out.places[`${id}:${n.id}`] = near.text;
        if (n.ports) out.ships[id] = { npc: n.id, ports: n.ports };
      }
    }
    return out;
  });
  const lines = [
    "// Generated by tools/world_index.cjs (run it again after moving a townsperson, a label or a way",
    "// out): the maps each map's ways out lead to, the ship captain of each port and the ports their",
    "// ship sails to, and the place each townsperson stands at (the nearest of its map's labels), as",
    "// \"map:npc\".",
    "",
    `export const MAP_LINKS: Record<string, string[]> = ${JSON.stringify(data.links, null, 1)};`,
    "",
    `export const SHIPS: Record<string, { npc: string; ports: string[] }> = ${JSON.stringify(data.ships, null, 1)};`,
    "",
    `export const NPC_PLACES: Record<string, string> = ${JSON.stringify(data.places, null, 1)};`,
    "",
  ];
  fs.writeFileSync(path.join(__dirname, "..", "src", "world_index.ts"), lines.join("\n"));
  console.log(Object.keys(data.links).length, "maps,", Object.keys(data.places).length, "townsfolk");
  await browser.close();
})();
